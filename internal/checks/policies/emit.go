package policies

import (
	"fmt"
	"sort"
	"strings"
)

var systemNamespaces = map[string]bool{
	"kube-system":     true,
	"kube-public":     true,
	"kube-node-lease": true,
	"istio-system":    true,
	"istio-cni":       true,
	"ztunnel":         true,
	"metallb-system":  true,
	"cert-manager":    true,
	"kyverno":         true,
}

// EmitPoliciesValues renders a schema-compliant values.yaml draft for console-charts/policies
// based on the target pod identity and discovered/simulated flows.
func EmitPoliciesValues(target TargetInfo, flows []Flow, policyNameOverride string) string {
	var b strings.Builder

	instance := firstNonEmpty(target.Pod.Metadata.Labels["ecpk/instance"], target.Namespace.Metadata.Labels["ecpk/instance"], "ed")
	cluster := firstNonEmpty(target.Pod.Metadata.Labels["ecpk/cluster"], target.Namespace.Metadata.Labels["ecpk/cluster"], "dev")
	project := firstNonEmpty(target.Pod.Metadata.Labels["ecpk/project"], target.Namespace.Metadata.Labels["ecpk/project"], sanitizeShortName(target.Namespace.Metadata.Name, 9))

	polName := sanitizePolicyName(policyNameOverride)
	if polName == "" {
		base := target.OwnerName
		if base == "" {
			base = target.Pod.Metadata.Name
		}
		polName = sanitizePolicyName(base)
	}

	b.WriteString("# Draft values.yaml for chart console-charts/policies\n")
	b.WriteString(fmt.Sprintf("# Generated by mesh-debug policies for %s/%s (kind=%s, sa=%s)\n",
		target.Namespace.Metadata.Name, target.Pod.Metadata.Name, target.WorkloadKind, target.ServiceAccount))
	b.WriteString("# Review selectors, identity tags, and verify rare/cron flows before applying.\n\n")

	b.WriteString("identity:\n")
	b.WriteString(fmt.Sprintf("  instance: %s\n", instance))
	b.WriteString(fmt.Sprintf("  cluster: %s\n", cluster))
	b.WriteString(fmt.Sprintf("  project: %s\n\n", project))

	// Group flows into:
	//  - appIngress: in-cluster ingress rules for policies[].ingress (with mirrors)
	//  - rawIngressIPs: non-pod ingress rules (e.g. kube-apiserver webhook) -> policies[].ingress[].from[].ipBlock
	//  - appEgress: in-cluster NON-system egress -> policies[].egress (with mirrors; no peer.serviceAccount!)
	//  - sysNetpolEgress: kube-apiserver (6443), CoreDNS (kube-system), istiod (istio-system) -> netpol[] (NO mirrors!)
	//  - externalNotes: external / ServiceEntry targets (commented guidance for egress-gateway or /32 netpol)

	type portSpec struct {
		Port     int
		Protocol string
	}
	type appPeerKey struct {
		NS      string
		SelKey  string
		SA      string
		Label   string
		Sources string
	}
	type appPeerGroup struct {
		Namespace string
		Selector  map[string]string
		SA        string
		Ports     map[portSpec]bool
		Sources   []string
	}

	appIngress := make(map[string]*appPeerGroup)
	appEgress := make(map[string]*appPeerGroup)
	var webhookIngressIPs []string
	webhookPorts := make(map[portSpec]bool)

	var apiServerIPs []string
	apiServerPort := 0
	needCoreDNS := false
	coreDNSPorts := make(map[portSpec]bool)
	needIstiod := false
	istiodPorts := make(map[portSpec]bool)

	type extTarget struct {
		Kind     string
		Label    string
		IP       string
		Port     int
		Protocol string
		Sources  string
	}
	var externalTargets []extTarget
	seenExt := make(map[string]bool)

	for _, f := range flows {
		proto := strings.ToUpper(f.Peer.Protocol)
		if proto == "" {
			proto = "TCP"
		}
		if f.Direction == "inbound" {
			port := f.LocalPort
			if port == 0 {
				port = f.Peer.Port
			}
			ps := portSpec{Port: port, Protocol: proto}
			if f.Peer.Kind == PeerKubeAPIServer {
				webhookIngressIPs = mergeUniqueStrs(webhookIngressIPs, f.Peer.effectiveIPs())
				webhookPorts[ps] = true
				continue
			}
			if f.Peer.Namespace != "" && !systemNamespaces[f.Peer.Namespace] {
				sel := effectivePeerSelector(f.Peer)
				key := fmt.Sprintf("%s|%s|%s", f.Peer.Namespace, selectorKey(sel), f.Peer.ServiceAccount)
				g, ok := appIngress[key]
				if !ok {
					g = &appPeerGroup{
						Namespace: f.Peer.Namespace,
						Selector:  sel,
						SA:        f.Peer.ServiceAccount,
						Ports:     make(map[portSpec]bool),
					}
					appIngress[key] = g
				}
				g.Ports[ps] = true
				g.Sources = mergeUniqueStrs(g.Sources, f.Sources)
			} else if f.Peer.IP != "" {
				webhookIngressIPs = mergeUniqueStrs(webhookIngressIPs, []string{f.Peer.IP})
				webhookPorts[ps] = true
			}
			continue
		}

		// Outbound
		ps := portSpec{Port: f.Peer.Port, Protocol: proto}
		switch f.Peer.Kind {
		case PeerKubeAPIServer:
			apiServerIPs = mergeUniqueStrs(apiServerIPs, f.Peer.effectiveIPs())
			apiServerPort = f.Peer.Port
			if apiServerPort == 0 {
				apiServerPort = 6443
			}
		case PeerCoreDNS:
			needCoreDNS = true
			coreDNSPorts[ps] = true
		case PeerIstiod:
			needIstiod = true
			istiodPorts[ps] = true
		case PeerService, PeerPod:
			if systemNamespaces[f.Peer.Namespace] {
				// Never put system namespaces into policies[] (would create mirror NP/AP in kube-system/istio-system!)
				if f.Peer.Namespace == "kube-system" {
					needCoreDNS = true
					coreDNSPorts[ps] = true
				} else if f.Peer.Namespace == "istio-system" {
					needIstiod = true
					istiodPorts[ps] = true
				}
				continue
			}
			sel := effectivePeerSelector(f.Peer)
			key := fmt.Sprintf("%s|%s", f.Peer.Namespace, selectorKey(sel))
			g, ok := appEgress[key]
			if !ok {
				g = &appPeerGroup{
					Namespace: f.Peer.Namespace,
					Selector:  sel,
					Ports:     make(map[portSpec]bool),
				}
				appEgress[key] = g
			}
			g.Ports[ps] = true
			g.Sources = mergeUniqueStrs(g.Sources, f.Sources)
		default:
			ek := fmt.Sprintf("%s|%s|%d|%s", f.Peer.Kind, f.Peer.IP, f.Peer.Port, proto)
			if !seenExt[ek] {
				seenExt[ek] = true
				externalTargets = append(externalTargets, extTarget{
					Kind:     f.Peer.Kind,
					Label:    f.Peer.DisplayName(),
					IP:       f.Peer.IP,
					Port:     f.Peer.Port,
					Protocol: proto,
					Sources:  strings.Join(f.Sources, ","),
				})
			}
		}
	}

	// 1. policies[] section (universal policies with mirrors for application-to-application traffic)
	if len(appIngress) == 0 && len(webhookIngressIPs) == 0 && len(appEgress) == 0 {
		b.WriteString("policies: []\n\n")
	} else {
		b.WriteString("policies:\n")
		b.WriteString(fmt.Sprintf("  - name: %s\n", polName))
		if target.ServiceAccount != "" {
			b.WriteString(fmt.Sprintf("    serviceAccount: %s\n", target.ServiceAccount))
		}
		writeYAMLSelector(&b, "    ", "selector", target.StableSelector)

		if len(appIngress) > 0 || len(webhookIngressIPs) > 0 {
			b.WriteString("    ingress:\n")
			inKeys := sortedGroupKeys(appIngress)
			for _, k := range inKeys {
				g := appIngress[k]
				b.WriteString(fmt.Sprintf("      # source: %s\n", strings.Join(g.Sources, ", ")))
				b.WriteString("      - from:\n")
				b.WriteString(fmt.Sprintf("          - namespace: %s\n", g.Namespace))
				if len(g.Selector) > 0 {
					writeYAMLSelector(&b, "            ", "selector", g.Selector)
				}
				if g.SA != "" {
					b.WriteString(fmt.Sprintf("            serviceAccount: %s\n", g.SA))
				}
				b.WriteString("        ports:\n")
				for _, ps := range sortedPortSpecs(g.Ports) {
					writeYAMLPort(&b, "          ", ps.Port, ps.Protocol)
				}
			}
			if len(webhookIngressIPs) > 0 {
				b.WriteString("      # Non-mesh / kube-apiserver webhook ingress (ipBlock, no mirror)\n")
				b.WriteString("      - from:\n")
				for _, ip := range webhookIngressIPs {
					b.WriteString("          - ipBlock:\n")
					b.WriteString(fmt.Sprintf("              cidr: %s/32\n", ip))
				}
				b.WriteString("        ports:\n")
				for _, ps := range sortedPortSpecs(webhookPorts) {
					writeYAMLPort(&b, "          ", ps.Port, ps.Protocol)
				}
			}
		}

		if len(appEgress) > 0 {
			b.WriteString("    egress:\n")
			egKeys := sortedGroupKeys(appEgress)
			for _, k := range egKeys {
				g := appEgress[k]
				b.WriteString(fmt.Sprintf("      # source: %s (chart auto-adds 15008/TCP for HBONE + mirrors NP/AP in %s)\n",
					strings.Join(g.Sources, ", "), g.Namespace))
				b.WriteString("      - to:\n")
				b.WriteString(fmt.Sprintf("          - namespace: %s\n", g.Namespace))
				if len(g.Selector) > 0 {
					writeYAMLSelector(&b, "            ", "selector", g.Selector)
				}
				b.WriteString("        ports:\n")
				for _, ps := range sortedPortSpecs(g.Ports) {
					writeYAMLPort(&b, "          ", ps.Port, ps.Protocol)
				}
			}
		}
		b.WriteString("\n")
	}

	// 2. netpol[] section (system / infrastructure egress WITHOUT mirrors in kube-system/istio-system)
	hasSysNetpol := len(apiServerIPs) > 0 || needCoreDNS || needIstiod
	if !hasSysNetpol {
		b.WriteString("netpol: []\n\n")
	} else {
		sysName := sanitizePolicyName(polName + "s")
		if sysName == polName {
			sysName = "sys"
		}
		b.WriteString("# System/infrastructure egress placed in netpol[] so no mirror NP/AP is created in kube-system/istio-system\n")
		b.WriteString("netpol:\n")
		b.WriteString(fmt.Sprintf("  - name: %s\n", sysName))
		writeYAMLSelector(&b, "    ", "selector", target.StableSelector)
		b.WriteString("    egress:\n")
		if len(apiServerIPs) > 0 {
			b.WriteString("      # kube-apiserver endpoints (post-DNAT IP + port 6443 required by Kube-OVN NetworkPolicy)\n")
			b.WriteString("      - to:\n")
			for _, ip := range apiServerIPs {
				b.WriteString("          - ipBlock:\n")
				b.WriteString(fmt.Sprintf("              cidr: %s/32\n", ip))
			}
			b.WriteString("        ports:\n")
			writeYAMLPort(&b, "          ", apiServerPort, "TCP")
		}
		if needCoreDNS {
			b.WriteString("      # CoreDNS (kube-system)\n")
			b.WriteString("      - to:\n")
			b.WriteString("          - namespaceSelector:\n")
			b.WriteString("              matchLabels:\n")
			b.WriteString("                kubernetes.io/metadata.name: kube-system\n")
			b.WriteString("        ports:\n")
			if len(coreDNSPorts) == 0 {
				writeYAMLPort(&b, "          ", 1053, "UDP")
				writeYAMLPort(&b, "          ", 53, "UDP")
			} else {
				for _, ps := range sortedPortSpecs(coreDNSPorts) {
					writeYAMLPort(&b, "          ", ps.Port, ps.Protocol)
				}
			}
		}
		if needIstiod {
			b.WriteString("      # istiod control plane (istio-system)\n")
			b.WriteString("      - to:\n")
			b.WriteString("          - namespaceSelector:\n")
			b.WriteString("              matchLabels:\n")
			b.WriteString("                kubernetes.io/metadata.name: istio-system\n")
			b.WriteString("        ports:\n")
			for _, ps := range sortedPortSpecs(istiodPorts) {
				writeYAMLPort(&b, "          ", ps.Port, ps.Protocol)
			}
		}
		b.WriteString("\n")
	}

	b.WriteString("authzpol: []\n")

	if len(externalTargets) > 0 {
		b.WriteString("\n# Observed external / ServiceEntry destinations (NOT added to 0.0.0.0/0 automatically):\n")
		if target.Ambient {
			b.WriteString("# For Ambient Mesh pods, external domains should go through the egress-gateway chart (ServiceEntry + waypoint + VEG).\n")
		}
		for _, ext := range externalTargets {
			b.WriteString(fmt.Sprintf("#   - %s (ip=%s, port=%d/%s, source=%s)\n",
				ext.Label, ext.IP, ext.Port, ext.Protocol, ext.Sources))
		}
	}

	return b.String()
}

func writeYAMLSelector(b *strings.Builder, indent, key string, sel map[string]string) {
	if len(sel) == 0 {
		b.WriteString(fmt.Sprintf("%s%s: {} # TODO: specify stable pod selector\n", indent, key))
		return
	}
	b.WriteString(fmt.Sprintf("%s%s:\n", indent, key))
	keys := make([]string, 0, len(sel))
	for k := range sel {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		b.WriteString(fmt.Sprintf("%s  %s: %q\n", indent, k, sel[k]))
	}
}

func writeYAMLPort(b *strings.Builder, indent string, port int, proto string) {
	if proto == "" || proto == "TCP" {
		b.WriteString(fmt.Sprintf("%s- port: %d\n", indent, port))
		return
	}
	b.WriteString(fmt.Sprintf("%s- port: %d\n", indent, port))
	b.WriteString(fmt.Sprintf("%s  protocol: %s\n", indent, proto))
}

func effectivePeerSelector(ep Endpoint) map[string]string {
	if len(ep.StableSelector) > 0 {
		return ep.StableSelector
	}
	return filterStablePodLabels(ep.Labels)
}

func selectorKey(sel map[string]string) string {
	keys := make([]string, 0, len(sel))
	for k := range sel {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, 0, len(keys))
	for _, k := range keys {
		parts = append(parts, k+"="+sel[k])
	}
	return strings.Join(parts, ",")
}

func sortedGroupKeys[T any](m map[string]T) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

type portSpecSorted struct {
	Port     int
	Protocol string
}

func sortedPortSpecs[T ~struct {
	Port     int
	Protocol string
}](m map[T]bool) []portSpecSorted {
	out := make([]portSpecSorted, 0, len(m))
	for ps := range m {
		out = append(out, portSpecSorted(ps))
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Port != out[j].Port {
			return out[i].Port < out[j].Port
		}
		return out[i].Protocol < out[j].Protocol
	})
	return out
}

// sanitizePolicyName produces a valid 2..6 char lowercase [a-z0-9-] name for console-charts/policies.
func sanitizePolicyName(raw string) string {
	s := sanitizeShortName(raw, 6)
	if len(s) < 2 {
		return "app"
	}
	return s
}

func sanitizeShortName(raw string, maxLen int) string {
	raw = strings.ToLower(strings.TrimSpace(raw))
	var b strings.Builder
	for _, r := range raw {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-' {
			b.WriteRune(r)
		}
	}
	s := strings.Trim(b.String(), "-")
	if len(s) > maxLen {
		s = strings.TrimRight(s[:maxLen], "-")
	}
	return s
}

func firstNonEmpty(vals ...string) string {
	for _, v := range vals {
		if strings.TrimSpace(v) != "" {
			return strings.TrimSpace(v)
		}
	}
	return ""
}

func mergeUniqueStrs(base, extra []string) []string {
	seen := make(map[string]bool, len(base)+len(extra))
	out := make([]string, 0, len(base)+len(extra))
	for _, s := range base {
		if s != "" && !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	for _, s := range extra {
		if s != "" && !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	sort.Strings(out)
	return out
}

// filterStablePodLabels strips ephemeral/pod-unique/Istio runtime labels so selectors remain valid across rollouts.
func filterStablePodLabels(labels map[string]string) map[string]string {
	if len(labels) == 0 {
		return nil
	}
	out := make(map[string]string)
	// Prefer well-known stable selector keys first.
	preferred := []string{
		"app.kubernetes.io/name",
		"app.kubernetes.io/component",
		"app.kubernetes.io/instance",
		"gateway.networking.k8s.io/gateway-name",
		"app",
	}
	for _, k := range preferred {
		if v, ok := labels[k]; ok && v != "" {
			out[k] = v
		}
	}
	if len(out) > 0 {
		return out
	}
	for k, v := range labels {
		if k == "pod-template-hash" ||
			k == "controller-revision-hash" ||
			k == "pod-template-generation" ||
			k == "statefulset.kubernetes.io/pod-name" ||
			strings.HasPrefix(k, "istio.io/") ||
			strings.HasPrefix(k, "security.istio.io/") ||
			strings.HasPrefix(k, "networking.istio.io/") {
			continue
		}
		out[k] = v
	}
	return out
}
